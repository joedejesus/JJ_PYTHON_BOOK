# Enunciado:
"""Escribe un programa que imprima la resta entre los números 5 y 3.5. Guarda estos valores  en  dos
variables de tipo entero y de punto  flotante,  respectivamente,  y  utiliza  estas  variables  para
realizar la operación. Guarda el resultado de la operación en una variable llamada "resta".  Además,
realiza lo mismo en una sola línea de código sin usar variables. En  ambos  casos,  usa  la  función
"print()" para mostrar el resultado en la consola."""

# Ejercicio_numeros_basicos_int_float_complex.py

# Explicación:
"""Definimos dos variables, una de tipo entero y otra de punto flotante, y les asignamos los valores
5 y 3.5, respectivamente. Luego, restamos ambas  variables  usando  el  operador  aritmético  (-)  y
guardamos el resultado en una variable llamada "resta". Finalmente, imprimimos el resultado  con  la
función "print()"."""

# Código:
numero_entero = 5
numero_flotante = 3.5

resta = numero_entero - numero_flotante
print(resta)

# Explicación:
"""Usamos una sola línea de código para  realizar  la  resta  entre  los  números  dados,  sin  usar
variables. Esto se logra escribiendo directamente los valores a restar con  el  operador  aritmético
(-) dentro de la función "print()". De esta manera, evitamos la  necesidad  de  crear  una  variable
adicional para  almacenar  el  resultado  de  la  operación.  Finalmente,  imprimimos  el  resultado
directamente."""

# Código:
print(5 - 3.5)

# Nota:
"""Es importante destacar que la función "print()" puede recibir expresiones como argumentos, lo que
permite  realizar  operaciones  directamente  dentro  de  ella  sin  necesidad  de  crear  variables
intermedias. Esto resulta útil para simplificar el  código  y  hacerlo  más  conciso  cuando  no  es
necesario almacenar el resultado de una operación para su uso posterior."""

