# Enunciado:
"""Los diccionarios (dict) en Python son estructuras que almacenan datos en pares clave-valor. Estos
pares organizan la información de forma estructurada. Los diccionarios  son  útiles  para  almacenar
datos relacionados entre sí. Cada elemento dentro  del  diccionario  tiene  una  clave  única;  esta
permite acceder a su valor correspondiente. Este tipo de dato corresponde al tipo (dict) en Python.

Además, los diccionarios son mutables, lo que permite modificarlos después de su  creación.  Existen
métodos y funciones para trabajar con diccionarios. Estos  métodos  y  funciones  permiten  agregar,
eliminar o modificar pares clave-valor, así como acceder  a  los  valores  almacenados  mediante  su
clave, entre otras funcionalidades que se explicarán en la sección correspondiente  a  "Diccionarios
(dict)"."""

