# Explicación:
"""Definimos una variable llamada "diccionario" y le asignamos  un  diccionario  que  contiene  tres
pares clave-valor. El primer par clave-valor tiene la clave "nombre" con el valor "Joe", el  segundo
par tiene la clave "edad" con el valor 33 y el tercer par tiene la clave "ubicacion"  con  el  valor
"Boo". Creamos el diccionario utilizando llaves {} para encerrar todo el conjunto.

Separamos los pares clave-valor con comas (,) y usamos dos puntos (:) para separar cada clave de  su
valor. Cada par sigue la sintaxis del tipo de dato correspondiente. Finalmente, imprimimos el  valor
de la variable "diccionario" en pantalla utilizando la función "print()"."""

# Código:
diccionario = {
    "nombre": "Joe",
    "edad": 33,
    "ubicacion": "Boo"
}
print(diccionario)

