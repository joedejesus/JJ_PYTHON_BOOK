# Enunciado:
"""En Python, es posible asignar múltiples valores a varias variables simultáneamente  en  una  sola
línea de código. El orden de asignación es crucial porque cada variable recibe su valor de izquierda
a derecha. Esto significa que la primera variable recibe el primer valor, la segunda variable recibe
el segundo valor y así sucesivamente."""

# Ejemplo_asignar_multiples_valores_a_variables.py

# Explicación:
"""Definimos tres variables en una sola línea de código: a, b y c, y les asignamos los  valores  10,
20 y 30 respectivamente. Separamos tanto las variables como  los  valores  con  comas,  lo  cual  es
esencial para realizar la asignación múltiple. Luego imprimimos los valores de las variables a, b  y
c en una sola línea  utilizando  la  función  "print()",  y  también  los  imprimimos  por  separado
acompañados de un texto descriptivo (concatenación). Esto muestra los valores de  las  variables  de
una manera más clara y legible.  De  esta  forma,  verificamos  que  los  valores  se  han  asignado
correctamente. El resultado será 10, 20 y 30, ya que el orden de asignación  sigue  de  izquierda  a
derecha."""

# Código:
a, b, c = 10, 20, 30
print(a, b, c)

print("El valor de a es:", a)
print("El valor de b es:", b)
print("El valor de c es:", c)

# Nota Importante:
"""Puedes asignar valores de diferentes tipos a las variables de esta misma forma, siempre y  cuando
el número de variables coincida con el número de valores a asignar.  Las  variables  y  los  valores
deben estar separados por comas, y los valores deben seguir la sintaxis propia de cada uno de ellos.
Esto ofrece gran flexibilidad en la programación, ya que puedes agrupar diferentes tipos de datos en
una sola línea."""

