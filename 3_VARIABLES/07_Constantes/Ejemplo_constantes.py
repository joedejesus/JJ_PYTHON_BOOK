# Enunciado:
"""Las constantes  en  Python  se  definen,  por  convención,  como  variables  escritas  en  letras
mayúsculas. Esto significa que no deben modificarse. Aunque es posible hacerlo, no es  recomendable,
ya que al declarar una constante se espera que su valor permanezca igual a lo  largo  del  programa.
Esto implica que el valor de la constante no debe cambiar."""

# Ejemplo_constantes.py

# Explicación:
"""Definimos la constante "PI" como una variable  escrita  en  mayúsculas.  Le  asignamos  un  valor
constante, en este caso el valor de "PI", e imprimimos su valor utilizando la función "print()".  En
el siguiente bloque de código, modificamos el valor de la constante "PI", lo cual es posible,  y  lo
imprimimos nuevamente. Esto demuestra que es posible cambiar el valor de una constante, pero  no  es
una práctica recomendada."""

# Código:
PI = 3.14159265359
print(PI)

PI = 0.44444444444
print(PI)

# Nota Importante:
"""Python no arroja un error al cambiar el valor de una constante. Esto significa  que,  aunque  sea
posible hacerlo, no se deben modificar las constantes, ya que  esto  va  en  contra  de  las  buenas
prácticas."""

