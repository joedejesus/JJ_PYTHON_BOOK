# Enunciado:
"""Una variable es un contenedor que almacena datos, tiene un nombre y puede cambiar su valor con el
tiempo. Las variables pueden almacenar diferentes  tipos  de  datos,  como  números,  resultados  de
operaciones matemáticas, bytes,  booleanos,  cadenas  de  texto,  conjuntos,  listas,  diccionarios,
tuplas, objetos, funciones, clases e incluso otras variables de  distintos  tipos  de  datos,  entre
otros. Además de almacenar datos, las variables se usan para realizar operaciones  y  cálculos,  así
como para controlar el flujo de un programa.

Las variables  son  fundamentales  en  la  programación,  ya  que  permiten  almacenar  y  manipular
información de manera eficiente. En Python, las variables son dinámicas, lo que significa que no  es
necesario declarar su tipo de dato al momento de crearlas, ya que Python lo infiere  automáticamente
a partir del valor que se les asigna."""

# Ejemplo_variables.py

# Explicación:
"""Definimos varias variables con nombres descriptivos según el tipo de dato  que  contienen  y  les
asignamos diferentes valores. Finalmente, imprimimos el valor de cada variable utilizando la función
"print()" para mostrar su contenido."""

# Código:
numero = 10
print(numero)

operacion = (5 + 3)
print(operacion)

secuencia_de_bytes = bytes("Hola, mundo.")
print(secuencia_de_bytes)

booleano = True
print(booleano)

cadena_de_texto = "Hola, mundo."
print(cadena_de_texto)

conjunto = {1, 2, 3, 4, 5}
print(conjunto)

lista = [1, 2, 3, 4, 5]
print(lista)

diccionario = {"clave_1": "Valor_1", "clave_2": "Valor_2"}
print(diccionario)

tupla = (1, 2, 3, 4, 5)
print(tupla)

objeto = {"nombre": "Joe", "edad": 33}
print(objeto)

def funcion(x, y): return (x + y)
print(funcion(2, 3))

clase = type(numero)
print(clase)

variable = booleano
print(variable)

