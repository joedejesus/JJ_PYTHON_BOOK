# Enunciado:
"""El sistema "ASCII", que significa American Standard  Code  for  Information  Interchange,  es  un
conjunto de caracteres ampliamente utilizado para representar texto en computadoras  y  dispositivos
electrónicos. Cada carácter, como letras, números y símbolos, corresponde a un número entero  en  el
rango de 0 a 127. Por ejemplo, la letra "A" corresponde al número 65, mientras que  el  carácter  de
espacio corresponde al número 32. Este sistema de codificación permite convertir texto  legible  por
humanos en una forma que las máquinas puedan procesar y  almacenar.  Además,  "ASCII"  establece  un
estándar universal que facilita la comunicación entre diferentes sistemas y plataformas,  asegurando
que los datos textuales sean interpretados de manera consistente y precisa.

Aunque su alcance es limitado para idiomas que requieren muchos símbolos  o  caracteres  especiales,
como el chino o el árabe, "ASCII" es la base de muchas otras codificaciones modernas, como "UTF-8" e
"ISO-8859-1". Estas codificaciones amplían el rango de caracteres  disponibles,  pero  conservan  la
compatibilidad con "ASCII" en los primeros 128 caracteres. Por  esta  razón,  "ASCII"  sigue  siendo
fundamental para  comprender  el  procesamiento  de  texto  y  su  representación  en  programación.
Comprender "ASCII" es esencial para trabajar con datos textuales, manipular cadenas de caracteres  y
garantizar  la  interoperabilidad   entre   sistemas   informáticos   en   diversos   lenguajes   de
programación."""

