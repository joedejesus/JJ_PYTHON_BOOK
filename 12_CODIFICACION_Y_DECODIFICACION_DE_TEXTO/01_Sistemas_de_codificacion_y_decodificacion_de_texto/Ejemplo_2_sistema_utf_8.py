# Enunciado:
"""El sistema "UTF-8" es una codificación de caracteres ampliamente utilizada que puede  representar
todos los caracteres de "Unicode". A diferencia de "ASCII", que solo cubre los caracteres del  0  al
127, "UTF-8" puede codificar una gran variedad de símbolos de diferentes idiomas, incluidos acentos,
símbolos matemáticos y emojis. Utiliza entre 1 y 4 bytes por carácter, lo que la  hace  eficiente  y
compatible con "ASCII".

El sistema "UTF-8" es fundamental para el procesamiento de  texto  moderno  y  la  interoperabilidad
entre sistemas. Además, es la codificación predeterminada en  muchas  plataformas  y  protocolos  de
Internet, lo que garantiza que los datos se puedan compartir y  comprender  de  manera  uniforme  en
diferentes sistemas y aplicaciones. Su diseño escalable permite representar caracteres sencillos con
un solo byte, mientras que los caracteres más complejos utilizan  múltiples  bytes,  manteniendo  un
equilibrio entre eficiencia y flexibilidad.

y aunque versiones históricas de "UTF-8" contemplaban hasta 6 bytes para representar caracteres,  en
la práctica moderna se limita a 4 bytes. Esto lo convierte  en  una  herramienta  esencial  para  el
desarrollo de software globalizado y el manejo de datos multilingües.

Además, Python utiliza "UTF-8" como codificación predeterminada para archivos fuente y literales  de
texto. Esto significa que, al escribir código en Python, es posible incluir caracteres de  cualquier
idioma sin preocuparse por problemas de codificación, lo que facilita la  creación  de  aplicaciones
internacionales y el manejo de datos multilingües. Esta característica es  especialmente  importante
en un mundo cada vez más globalizado, donde la  capacidad  de  trabajar  con  diferentes  idiomas  y
conjuntos de caracteres es esencial para el éxito de las aplicaciones y servicios digitales."""

