# Enunciado:
"""El sistema "Unicode" es un estándar de codificación universal que abarca todos los caracteres  de
todos los sistemas de escritura del mundo, incluidos alfabetos, ideogramas, símbolos y emojis.  Este
estándar asigna un número único a cada carácter,  denominado  "punto  de  código",  lo  que  elimina
conflictos en la representación de textos en múltiples idiomas y plataformas. Gracias  a  "Unicode",
se garantiza la coherencia en la representación, el almacenamiento y la  manipulación  del  texto  a
nivel mundial, independientemente del idioma o del sistema operativo.

Además, "Unicode" se relaciona con  sistemas  de  codificación  como  "ASCII",  cuyo  repertorio  de
caracteres es un subconjunto compatible, y con "UTF-8", que es una de las formas más utilizadas para
codificar caracteres. "UTF-8"  es  eficiente  porque  utiliza  un  número  variable  de  bytes  para
representar caracteres, optimizando el almacenamiento y la  compatibilidad  con  sistemas  modernos.
Este estándar es esencial para el desarrollo de aplicaciones globales y la  interoperabilidad  entre
sistemas que manejan texto en diferentes idiomas y formatos."""

