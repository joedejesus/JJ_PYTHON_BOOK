# Código:
Lista_de_las_funciones_incorporadas_para_conversion_de_tipos = [

    # Funciones relacionadas con caracteres y cadenas.
    "ord()",         # Devuelve el valor Unicode de un carácter.
    "chr()",         # Convierte un valor Unicode a su carácter correspondiente.
    "ascii()",       # Convierte un objeto a su representación "ASCII".
    "repr()",        # Devuelve la representación en cadena de un objeto, que puede ser evaluada por "eval()".

    # Funciones relacionadas con la ejecución de código.
    "eval()",        # Evalúa una cadena como código Python.
    "exec()",        # Ejecuta una cadena como código Python.

    # Funciones relacionadas con el entorno y variables.
    "globals()",     # Devuelve el diccionario de variables globales.
    "locals()",      # Devuelve el diccionario de variables locales.
    "vars()",        # Devuelve el atributo "__dict__" de un objeto o el diccionario de variables locales si no se pasa ningún objeto.

    # Funciones relacionadas con tipos y clases.
    "callable()",    # Devuelve "True" si el objeto es invocable (puede ser llamado como una función).
    "isinstance()",  # Comprueba si un objeto es una instancia de una clase o de una tupla de clases.
    "issubclass()",  # Comprueba si una clase es una subclase de otra clase o de una tupla de clases.
    "type()",        # Devuelve el tipo de un objeto.

    # Otras funciones útiles.
    "id()",          # Devuelve el identificador único de un objeto.
    "hash()",        # Devuelve el hash de un objeto.
]

