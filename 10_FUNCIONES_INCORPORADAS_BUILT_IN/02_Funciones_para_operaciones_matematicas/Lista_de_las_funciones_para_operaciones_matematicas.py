    # Operaciones matemáticas básicas.
    "abs()",      # Devuelve el valor absoluto de un número.
    "divmod()",   # Devuelve el cociente y el resto de una división como una tupla.
    "pow()",      # Calcula la potencia de un número (equivalente a **).
