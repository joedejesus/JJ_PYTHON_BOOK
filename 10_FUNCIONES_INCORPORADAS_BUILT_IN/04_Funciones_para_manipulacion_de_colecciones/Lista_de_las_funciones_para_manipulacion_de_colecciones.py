    # Funciones para obtener información sobre colecciones.
    "len()",        # Devuelve la longitud (número de elementos) de un objeto.
    "max()",        # Devuelve el elemento mayor de un iterable o el mayor de dos o más argumentos.
    "min()",        # Devuelve el elemento menor de un iterable o el menor de dos o más argumentos.
    "sum()",        # Devuelve la suma de los elementos de un iterable.
