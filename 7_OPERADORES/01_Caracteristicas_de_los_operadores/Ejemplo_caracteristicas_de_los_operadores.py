# Enunciado:
"""Los operadores en Python son símbolos especiales o palabras clave que permiten realizar  diversas
operaciones sobre operandos, como variables, constantes o expresiones. Son una  parte  esencial  del
lenguaje, porque facilitan expresar instrucciones de manera clara y eficiente.

En Python, existen operadores que abarcan desde operaciones aritméticas básicas hasta comparaciones,
asignaciones, evaluaciones lógicas, manipulaciones de  estructuras  de  datos  y  verificaciones  de
identidad o pertenencia.

Estos operadores permiten construir algoritmos que interactúan  dinámicamente  con  la  información.
Además, Python sigue una jerarquía que determina la precedencia de los  operadores  y  el  orden  de
evaluación. Esto resulta fundamental para evitar errores lógicos y  escribir  código  de  forma  más
eficiente."""

