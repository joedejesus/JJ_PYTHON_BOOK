    "6. Operaciones comunes:",  # Acceso por clave, inserción, eliminación y actualización de pares clave-valor.
    "7. Iteración:",            # Se pueden recorrer por claves, valores o pares clave-valor con bucles.
    "8. Subdiccionarios:",      # Pueden contener otros diccionarios como valores.
    "9. Métodos específicos:",  # Métodos como ".keys()", ".values()", ".items()", ".get()", etc.
    "10. Comparación:",         # Se pueden comparar con operadores como (==) y (!=).
    "11. Longitud:",            # Su longitud se puede determinar con "len()".
