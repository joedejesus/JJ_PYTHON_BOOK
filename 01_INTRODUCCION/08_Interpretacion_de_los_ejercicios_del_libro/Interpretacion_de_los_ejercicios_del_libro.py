"""Los ejercicios de "JJ_PYTHON_BOOK" están pensados para  que  pongas  en  práctica  cada  concepto
escribiendo el código por tu cuenta. Cada uno presenta un enunciado  que  expone  el  problema,  una
explicación que desarrolla la lógica paso a paso, una solución escrita  con  claridad  y  notas  que
añaden detalles importantes para reforzar lo aprendido.

Interpretar un ejercicio consiste en leer el enunciado  con  atención,  comprender  la  situación  y
seguir la explicación para ver cómo se construye la solución. Después,  puedes  estudiar  el  código
final y volver a escribirlo desde cero, aplicando la lógica que acabas de aprender. Ese  proceso  de
borrar, reconstruir y ajustar el código es lo que convierte el concepto en conocimiento real.

Los ejercicios no buscan ponerte a prueba, sino ayudarte a transformar ideas en código mediante  una
práctica consciente. Si lees, entiendes y reconstruyes  el  código  con  calma,  cada  ejercicio  te
permitirá afianzar el concepto que estás estudiando."""

