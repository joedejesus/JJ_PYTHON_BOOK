# Nota Muy Importante:
"""Para referirse a los nombres de los constructores de objetos básicos, se utilizan las  notaciones
de tipo o clase: "int()", "float()", "complex()", "bool()", "str()", "list()", "tuple()", "range()",
"set()", "frozenset()" y "dict()". En todos los casos, se acompaña cada notación con paréntesis  (),
ya que se trata de constructores de objetos básicos y estos pueden recibir un parámetro o  argumento
para crear un objeto de su tipo o clase correspondiente.

Es importante destacar que, en realidad, estos constructores son funciones integradas (built-in)  en
Python, pero se les llama constructores de objetos básicos porque  su  función  principal  es  crear
instancias u objetos de su tipo o clase correspondiente.

Por ejemplo, "int()" es un constructor que crea un objeto de tipo entero, "float()" crea  un  objeto
de tipo flotante, "str()" crea un objeto de tipo cadena de  texto,  y  así  sucesivamente.  En  esta
biblioteca se les llama constructores de objetos básicos para enfatizar su papel fundamental  en  la
creación de objetos de diferentes  tipos  y  clases  en  Python  y,  de  esta  forma,  facilitar  la
comprensión de su función y uso en el contexto de la programación en Python."""

