# Enunciado:
"""En Python, los constructores de objetos básicos son: "int()", "float()",  "complex()",  "bool()",
"str()", "list()", "tuple()", "range()", "set()",  "frozenset()"  y  "dict()".  Estos  constructores
corresponden a los tipos o clases de datos predefinidos en Python, ya que permiten crear  instancias
u objetos de su tipo o clase correspondiente.

Al usar estos constructores, es posible crear, convertir y organizar los tipos  de  datos  de  forma
precisa  y  eficiente.  Cada  tipo  de  dato  presenta  características  particulares  en  cuanto  a
comportamiento, mutabilidad y uso típico.

Además, estos constructores facilitan la interacción con estructuras de datos y algoritmos,  ya  que
proporcionan una base uniforme sobre la cual  construir  operaciones  más  complejas.  Comprenderlos
permite implementar soluciones efectivas, anticipar posibles errores y optimizar el rendimiento  del
código. Estos constructores son  esenciales  para  manipular  información  de  manera  eficaz  y  se
consideran pilares del paradigma orientado a objetos en Python,  dado  que  todo  en  Python  es  un
objeto, incluso los tipos de datos más simples."""

