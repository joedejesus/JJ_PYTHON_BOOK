lista_de_los_metodos_especificos_y_aplicables_para_bytes = [

    # Métodos de bytes y de bytearray.
    ".encode()",             # Codifica una cadena en un objeto bytes usando un esquema de codificación (p. ej., UTF-8, ASCII).
    ".decode()",             # Decodifica un objeto bytes en una cadena usando un esquema de codificación (p. ej., UTF-8, ASCII).

    # Métodos de codecs para codificar y decodificar.
    ".codecs.encode()",      # Codifica un objeto usando un esquema de codificación específico (p. ej., UTF-8, ASCII).
    ".codecs.decode()",      # Decodifica un objeto usando un esquema de codificación específico (p. ej., UTF-8, ASCII).

    # Métodos de codecs para obtener información sobre esquemas de codificación.
    ".codecs.getencoder()",  # Devuelve un codificador para un esquema específico (p. ej., UTF-8, ASCII).
    ".codecs.getdecoder()",  # Devuelve un decodificador para un esquema específico (p. ej., UTF-8, ASCII).
    ".codecs.lookup()"       # Busca un esquema de codificación registrado (p. ej., UTF-8, ASCII). 
]

