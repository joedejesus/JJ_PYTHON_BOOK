# Codigo:
lista_de_los_metodos_especificos_y_aplicables_para_conjuntos = [

    # Métodos de modificación y copia.
    ".add()",                          # Agrega un elemento al conjunto.
    ".remove()",                       # Elimina un elemento y lanza una excepción si no existe.
    ".discard()",                      # Elimina un elemento si existe, sin lanzar una excepción.
    ".pop()",                          # Elimina y devuelve un elemento arbitrario.
    ".clear()",                        # Elimina todos los elementos del conjunto.
    ".copy()",                         # Devuelve una copia superficial del conjunto.

    # Métodos de operaciones entre conjuntos.
    ".union()",                        # Devuelve la unión de los conjuntos.
    ".update()",                       # Actualiza el conjunto con la unión de otros.
    ".difference()",                   # Devuelve la diferencia entre los conjuntos.
    ".difference_update()",            # Actualiza el conjunto eliminando elementos comunes con otros.
    ".intersection()",                 # Devuelve la intersección de los conjuntos.
    ".intersection_update()",          # Actualiza el conjunto con la intersección.
    ".symmetric_difference()",         # Devuelve la diferencia simétrica entre los conjuntos.
    ".symmetric_difference_update()",  # Actualiza el conjunto con la diferencia simétrica.

    # Métodos de verificación.
    ".isdisjoint()",                   # Verifica si dos conjuntos son disjuntos.
    ".issubset()",                     # Verifica si un conjunto es subconjunto de otro.      
    ".issuperset()"                    # Verifica si un conjunto es superconjunto de otro.
]

