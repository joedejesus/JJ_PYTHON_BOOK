# Código:
lista_de_los_metodos_especificos_y_aplicables_para_diccionarios = [

    # Métodos de acceso.
    ".get()",         # Devuelve el valor de una clave, o un valor por defecto.
    ".keys()",        # Devuelve una vista de las claves.
    ".values()",      # Devuelve una vista de los valores.
    ".items()",       # Devuelve una vista de pares clave-valor.

    # Métodos de modificación y copia.
    ".pop()",         # Elimina una clave y devuelve su valor.
    ".popitem()",     # Elimina y devuelve el último par clave-valor insertado.
    ".setdefault()",  # Devuelve el valor de una clave, o lo establece si no existe.
    ".update()",      # Actualiza el diccionario con pares clave-valor de otro diccionario.
    ".clear()",       # Elimina todos los elementos del diccionario.
    ".copy()",        # Devuelve una copia superficial del diccionario.

    # Método de creación.
    ".fromkeys()"     # Crea un nuevo diccionario con claves de un iterable y un mismo valor.
]

