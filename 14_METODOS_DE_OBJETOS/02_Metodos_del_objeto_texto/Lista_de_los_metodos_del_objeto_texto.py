# Código:
lista_de_los_metodos_especificos_y_aplicables_para_texto = [

    # Métodos de transformación de texto.
    ".capitalize()",    # Convierte el primer carácter en mayúscula.
    ".lower()",         # Convierte el texto a minúsculas.
    ".upper()",         # Convierte el texto a mayúsculas.
    ".swapcase()",      # Invierte mayúsculas y minúsculas.
    ".title()",         # Convierte el texto a formato de título.
    ".casefold()",      # Convierte el texto a minúsculas de forma más agresiva que ".lower()".

    # Métodos para eliminar espacios en blanco.
    ".strip()",         # Elimina espacios en blanco a ambos lados.
    ".lstrip()",        # Elimina espacios en blanco a la izquierda.
    ".rstrip()",        # Elimina espacios en blanco a la derecha.

    # Métodos de alineación.
    ".center()",        # Centra el texto en un ancho especificado.
    ".ljust()",         # Justifica el texto a la izquierda en un ancho especificado.
    ".rjust()",         # Justifica el texto a la derecha en un ancho especificado.
    ".zfill()",         # Rellena el texto con ceros a la izquierda.

    # Métodos de búsqueda.
    ".startswith()",    # Verifica si el texto comienza con una subcadena.
    ".endswith()",      # Verifica si el texto termina con una subcadena.
    ".count()",         # Cuenta las ocurrencias de una subcadena.
    ".find()",          # Encuentra la primera ocurrencia de una subcadena.
    ".rfind()",         # Encuentra la última ocurrencia de una subcadena.
    ".index()",         # Encuentra la primera ocurrencia de una subcadena (lanza una excepción si no existe).
    ".rindex()",        # Encuentra la última ocurrencia de una subcadena (lanza una excepción si no existe).

    # Métodos de división y unión.
    ".split()",         # Divide el texto en una lista.
    ".rsplit()",        # Divide el texto en una lista desde la derecha.
    ".splitlines()",    # Divide el texto en líneas.
    ".join()",          # Une una secuencia de cadenas con el texto como separador.

    # Métodos de reemplazo y partición.
    ".replace()",       # Reemplaza ocurrencias de una subcadena por otra.
    ".partition()",     # Divide el texto en tres partes usando un separador.
    ".rpartition()",    # Similar a ".partition()", pero busca desde la derecha.

    # Otros métodos.
    ".expandtabs()",    # Reemplaza tabulaciones con espacios.
    ".format()",        # Formatea el texto usando marcadores de posición.
    ".format_map()",    # Similar a ".format()", pero usa un diccionario.
    ".translate()",     # Traduce caracteres usando una tabla de traducción.

    # Métodos de verificación.
    ".isalnum()",       # Verifica si todos los caracteres son alfanuméricos.
    ".isalpha()",       # Verifica si todos los caracteres son alfabéticos.
    ".isascii()",       # Verifica si todos los caracteres son "ASCII".
    ".isdecimal()",     # Verifica si todos los caracteres son decimales.
    ".isdigit()",       # Verifica si todos los caracteres son dígitos.
    ".isidentifier()",  # Verifica si el texto es un identificador válido.
    ".islower()",       # Verifica si todos los caracteres están en minúsculas.
    ".isnumeric()",     # Verifica si todos los caracteres son numéricos.
    ".isprintable()",   # Verifica si todos los caracteres son imprimibles.
    ".isspace()",       # Verifica si todos los caracteres son espacios en blanco.
    ".istitle()",       # Verifica si el texto está en formato título.
    ".isupper()"        # Verifica si todos los caracteres están en mayúsculas.
]

