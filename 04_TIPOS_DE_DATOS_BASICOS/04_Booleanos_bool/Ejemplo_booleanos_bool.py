# Explicación:
"""Definimos  dos  variables  (a  y  b)  y  les  asignamos  un  valor  booleano  (True   y   False),
respectivamente. Luego, definimos dos variables (x e y) y les asignamos los valores enteros 5 y  10,
respectivamente. Después, comparamos si "x" es mayor que "y" utilizando el operador  de  comparación
(>) entre las dos variables que contienen los  números  enteros  y  guardamos  el  resultado  en  la
variable "comparacion". Finalmente, imprimimos el resultado utilizando la función "print()". En este
caso, el resultado de la comparación será False, porque 5 no es mayor que 10."""

# Código:
a = True
b = False

x = 5
y = 10

comparacion = (x > y)
print(comparacion)

# Nota Importante:
"""No es necesario declarar variables booleanas explícitamente (como a  y  b),  ya  que  Python,  al
realizar una comparación, siempre devuelve un valor booleano. Sin embargo, en este  ejemplo  se  las
incluye para ilustrar el concepto de los booleanos y su sintaxis.

Además, es importante recordar que ambos valores booleanos (True y  False)  son  del  tipo  de  dato
(bool) en Python, y que se debe usar la primera letra en mayúscula al definirlos."""

