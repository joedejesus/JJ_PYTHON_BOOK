# Enunciado:
"""Los booleanos (bool) representan valores lógicos en Python, es decir, verdadero  (True)  o  falso
(False). Se utilizan con frecuencia en condiciones y comparaciones. Los booleanos controlan el flujo
de un programa porque permiten tomar decisiones basadas en condiciones específicas.

En Python, se crean utilizando las palabras clave "True" y "False", con la primera letra siempre  en
mayúscula. El tipo de dato más pequeño en Python es el booleano, que representa  dos  valores:  True
(verdadero) y  False  (falso),  equivalentes  a  "1"  y  "0",  respectivamente.  Un  booleano  puede
interpretarse como un bit en términos de valores posibles."""

