# Enunciado:
"""Python clasifica los números  en  tres  tipos:  números  enteros,  números  decimales  y  números
complejos. Los números enteros (int) se escriben sin decimales y pueden tener signo positivo  (+)  o
negativo (-). Los números decimales (float) se escriben con un punto (.) como  separador  decimal  y
también pueden tener signo positivo (+) o negativo (-).

Los números complejos (complex) se definen como la suma de una parte real y  una  parte  imaginaria,
usando la letra "j"  para  la  parte  imaginaria.  Por  ejemplo,  (4j)  representa  cuatro  unidades
imaginarias (4 jotas). Para definir un número complejo, se usa la notación (a + 4j), donde "a" es la
parte real y "4j" es la parte imaginaria. Ambas partes, la real (a) y la imaginaria (4j), forman  el
número complejo.

Con  estos  tipos  de  números  se  pueden  realizar  operaciones  matemáticas  como  suma,   resta,
multiplicación y división,  además  de  operaciones  más  avanzadas  como  exponenciación  y  raíces
cuadradas, entre otras. Se recomienda usar paréntesis para indicar el orden  de  las  operaciones  y
mejorar la legibilidad del código."""

# Ejemplo_numeros_basicos_int_float_complex.py

# Explicación:
"""Definimos una variable llamada "numero_entero" que almacena un número entero, en  este  caso,  un
número negativo. El tipo de dato de esta variable es (int). Finalmente, mostramos  el  valor  de  la
variable en la consola con la función "print()"."""

# Código:
numero_entero = -5
print(numero_entero)

# Explicación:
"""Definimos una variable llamada "numero_decimal" que almacena un número decimal, en este caso,  un
número positivo con decimales. Usamos un punto (.) para separar la parte entera de la parte decimal,
no una coma (,). El tipo de dato de esta variable es (float). Finalmente, mostramos el valor  de  la
variable en la consola con la función "print()"."""

# Código:
numero_decimal = 6.022
print(numero_decimal)

# Explicación:
"""Definimos una variable llamada "numero_complejo" que almacena un número complejo; en  este  caso,
su parte real resulta de la suma de dos números enteros y su parte imaginaria  es  (4j).  Usamos  la
letra "j" para representar la parte  imaginaria  del  número  complejo,  acompañada  del  número  de
unidades imaginarias "4". Además, usamos paréntesis para indicar el orden  de  las  operaciones.  El
tipo de dato de esta variable es (complex). Finalmente, mostramos el valor  de  la  variable  en  la
consola con la función "print()"."""

# Código:
numero_complejo = (3 + 2) + (4j)
print(numero_complejo)  # El resultado será (5 + 4j).

# Nota Importante:
"""Usamos un punto (.) como separador decimal para los números decimales (float), no una  coma  (,).
Además, usamos la letra "j" para representar la parte imaginaria de los números complejos (complex).
Es importante recordar que los números complejos se definen como la suma de una parte real (a) y una
parte imaginaria (4j), y que la parte imaginaria se representa  con  la  letra  "j"  acompañada  del
número de unidades imaginarias, en este caso, "4". Finalmente, se recomienda  usar  paréntesis  para
indicar el orden de las operaciones y mejorar la legibilidad del código."""

