lista_de_los_contructores_de_objetos_basicos = [

    "int()",        # Convierte un número o una cadena en un número entero.
    "float()",      # Convierte un número o una cadena en un número de punto flotante.
    "complex()",    # Crea un número complejo a partir de dos números (parte real y parte imaginaria).
    "bool()",       # Convierte un valor en un booleano (True o False).
    "str()",        # Convierte un objeto en una cadena de texto.
    "list()",       # Crea una lista a partir de un iterable.
    "tuple()",      # Crea una tupla a partir de un iterable.
    "range()",      # Crea un objeto de rango, que es un iterable de números enteros.
    "set()",        # Crea un conjunto a partir de un iterable.
    "frozenset()",  # Crea un conjunto inmutable a partir de un iterable.
    "dict()",       # Crea un diccionario a partir de un iterable de pares clave-valor.
]

# Nota Muy Importante:
"""Los constructores  de  objetos  básicos  son,  en  realidad,  funciones  incorporadas  de  Python
(built-in). Sin embargo, en esta biblioteca se les  llama  constructores  de  objetos  básicos  para
facilitar su comprensión  y  aprendizaje,  así  como  para  distinguirlos  de  las  demás  funciones
incorporadas. Por ello, a partir de esta sección se les llamará constructores de objetos básicos, ya
que su función principal es construir objetos básicos a partir de otros objetos o valores.

Aunque los constructores de bytes también son constructores de objetos básicos, se explicarán en  la
sección correspondiente a "Bytes", ya que primero es necesario comprender los  aspectos  básicos  de
los bytes para entender su uso y funcionamiento."""

