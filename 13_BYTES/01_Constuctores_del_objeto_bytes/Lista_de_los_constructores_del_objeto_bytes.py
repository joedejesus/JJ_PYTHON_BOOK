# Nota Muy Importante:
"""Estos constructores son  funciones  incorporadas  en  Python  (built-in)  que  permiten  crear  y
manipular objetos de bytes. Sin embargo, en esta biblioteca se les llama  constructores  del  objeto
bytes porque son funciones que construyen y manipulan objetos de bytes. Por ello, a partir  de  esta
sección se les tratará como constructores del objeto bytes para facilitar su comprensión y uso en el
contexto de esta biblioteca, aunque en realidad son funciones incorporadas que realizan  operaciones
sobre objetos de bytes."""

