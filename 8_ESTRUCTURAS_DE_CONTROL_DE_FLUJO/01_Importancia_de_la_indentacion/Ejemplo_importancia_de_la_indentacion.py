# Enunciado:
"""La indentación consiste en añadir espacios en blanco al  inicio  de  una  línea  de  código  para
indicar su nivel de anidamiento. En Python, este aspecto es esencial porque define la estructura del
programa y delimita los bloques de instrucciones. A diferencia de otros lenguajes que emplean llaves
({}) para agrupar código, Python se  basa  exclusivamente  en  la  indentación.  Esto  favorece  una
sintaxis más limpia, legible y fácil de mantener, además de reducir la probabilidad de errores.

La indentación no es solo una cuestión estética,  sino  un  requisito  obligatorio  en  Python.  Los
bloques de control de flujo como "if", "for" y "while", así  como  las  funciones,  clases  y  otras
estructuras, dependen de ella para establecer su alcance. Una indentación incorrecta puede  provocar
errores de sintaxis (IndentationError)  o  comportamientos  inesperados  durante  la  ejecución  del
programa.

Para aplicarla correctamente, cada nivel de indentación debe ser coherente a lo  largo  de  todo  el
archivo. Por ejemplo, si se utilizan 4 espacios para un nivel, este formato debe mantenerse siempre.
Es importante evitar mezclar espacios y tabulaciones, ya que esto puede generar errores difíciles de
detectar.

Como referencia, la guía de estilo oficial de Python, conocida como "PEP 8",  recomienda  emplear  4
espacios por nivel de indentación y evitar las tabulaciones, garantizando así uniformidad y claridad
en el código."""

