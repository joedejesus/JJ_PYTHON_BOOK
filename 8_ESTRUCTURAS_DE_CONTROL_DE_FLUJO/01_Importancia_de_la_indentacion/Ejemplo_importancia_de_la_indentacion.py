# Nota Muy Importante:
"""La  falta  de  indentación  o  una  indentación  incorrecta  provoca   un   error   de   sintaxis
(IndentationError). En Python, la indentación delimita bloques de control de flujo como "if",  "for"
y "while", así  como  funciones,  clases  y  otras  estructuras.  Mantener  una  buena  práctica  de
indentación no solo evita errores, sino que también mejora la colaboración en proyectos  y  facilita
la lectura y comprensión del código por parte de cualquier desarrollador que lo consulte.

Por último, es importante tener en cuenta que las herramientas de desarrollo, como editores de texto
y entornos de desarrollo integrado (IDEs), suelen incluir opciones para aplicar  automáticamente  la
indentación recomendada y resaltar posibles inconsistencias. Configurar estas herramientas de  forma
adecuada ayuda a prevenir errores, seguir las buenas prácticas establecidas  y  mantener  un  estilo
uniforme en todo el proyecto, lo que a su vez incrementa la calidad y mantenibilidad del código."""

